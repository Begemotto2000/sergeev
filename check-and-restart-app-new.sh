#!/bin/bash

echo "╔════════════════════════════════════════════════════════════════════════╗"
echo "║ ПРОВЕРКА И ПЕРЕЗАГРУЗКА ПРИЛОЖЕНИЯ                                    ║"
echo "╚════════════════════════════════════════════════════════════════════════╝"
echo ""

# ============================================================================
# ШАГ 1: Проверить статус Docker контейнера
# ============================================================================

echo "📍 ШАГ 1: Статус Docker контейнера"
echo ""

CONTAINER_ID=$(docker ps -q -f name=sergeev_digitization_system-app)

if [ -z "$CONTAINER_ID" ]; then
    echo "❌ Контейнер не найден!"
    echo ""
    echo "Все контейнеры:"
    docker ps -a
else
    echo "✅ Контейнер найден: $CONTAINER_ID"
    echo ""
    
    STATUS=$(docker inspect $CONTAINER_ID --format='{{.State.Status}}')
    echo "  Статус: $STATUS"
    
    if [ "$STATUS" != "running" ]; then
        echo "  ❌ Контейнер не работает!"
        echo ""
        echo "  Перезагружаю Docker Compose..."
        cd /opt/sergeev-100/sergeev_digitization_system
        docker-compose -f docker-compose.moscow.yml restart app
        sleep 5
    fi
fi

echo ""

# ============================================================================
# ШАГ 2: Проверить логи контейнера
# ============================================================================

echo "📍 ШАГ 2: Логи контейнера (последние 20 строк)"
echo ""

docker logs --tail 20 $CONTAINER_ID

echo ""

# ============================================================================
# ШАГ 3: Проверить что приложение слушает на 3000
# ============================================================================

echo "📍 ШАГ 3: Проверка портов"
echo ""

sleep 2

echo "  Процессы на порту 3000:"
lsof -i :3000 2>/dev/null | grep -v COMMAND || echo "    Порт 3000 не слушает никто!"

echo ""

# ============================================================================
# ШАГ 4: Проверить что приложение отвечает
# ============================================================================

echo "📍 ШАГ 4: Проверка доступности приложения"
echo ""

echo "  Запрос: GET http://localhost:3000/"
HTTP_STATUS=$(curl -s -o /dev/null -w "%{http_code}" http://localhost:3000/)
echo "  HTTP Status: $HTTP_STATUS"

if [ "$HTTP_STATUS" = "200" ]; then
    echo "  ✅ Приложение доступно на порту 3000!"
else
    echo "  ❌ Приложение не отвечает на порту 3000"
    echo ""
    echo "  Попытка получить ответ:"
    curl -s http://localhost:3000/ | head -10
fi

echo ""

# ============================================================================
# ШАГ 5: Проверить что Nginx может достучаться
# ============================================================================

echo "📍 ШАГ 5: Проверка Nginx → приложение"
echo ""

echo "  Запрос: GET http://localhost/ (через Nginx)"
HTTP_STATUS=$(curl -s -o /dev/null -w "%{http_code}" http://localhost/)
echo "  HTTP Status: $HTTP_STATUS"

if [ "$HTTP_STATUS" = "200" ]; then
    echo "  ✅ Nginx может достучаться до приложения!"
else
    echo "  ❌ Nginx не может достучаться"
fi

echo ""

# ============================================================================
# ШАГ 6: Проверить Nginx конфиг
# ============================================================================

echo "📍 ШАГ 6: Nginx конфиг"
echo ""

cat /etc/nginx/conf.d/app.conf

echo ""

# ============================================================================
# ФИНАЛЬНЫЙ ОТЧЕТ
# ============================================================================

echo "╔════════════════════════════════════════════════════════════════════════╗"
echo "║ ✅ ПРОВЕРКА ЗАВЕРШЕНА                                                  ║"
echo "╚════════════════════════════════════════════════════════════════════════╝"
echo ""
