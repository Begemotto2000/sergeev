#!/bin/bash
set -e

echo "╔════════════════════════════════════════════════════════════════════════╗"
echo "║ ШАГ 1.1: ПОДКЛЮЧЕНИЕ И ПРОВЕРКА СТАТУСА DOCKER COMPOSE               ║"
echo "╚════════════════════════════════════════════════════════════════════════╝"
echo ""

cd /opt/sergeev-100 2>/dev/null || mkdir -p /opt/sergeev-100

echo "📍 Текущая директория: $(pwd)"
echo ""

echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "1️⃣  Проверка Docker Compose статуса"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
if [ -f "docker-compose.moscow.yml" ]; then
    echo "✅ Файл docker-compose.moscow.yml найден"
    docker-compose -f docker-compose.moscow.yml ps 2>/dev/null || echo "⚠️  Docker Compose не запущен или контейнеры остановлены"
else
    echo "⚠️  Файл docker-compose.moscow.yml не найден"
fi
echo ""

echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "2️⃣  Проверка всех контейнеров Docker"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
docker ps -a || echo "⚠️  Docker не установлен или не работает"
echo ""

echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "3️⃣  Проверка использования портов"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
netstat -tlnp 2>/dev/null | grep LISTEN || echo "⚠️  netstat не доступен"
echo ""

echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "4️⃣  Остановка Docker Compose (для миграции на K8s)"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
if [ -f "docker-compose.moscow.yml" ]; then
    docker-compose -f docker-compose.moscow.yml down 2>/dev/null && echo "✅ Docker Compose остановлен" || echo "⚠️  Docker Compose уже остановлен"
else
    echo "⚠️  Файл docker-compose.moscow.yml не найден"
fi
echo ""

echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "5️⃣  Проверка, что все контейнеры остановлены"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
RUNNING=$(docker ps -q | wc -l)
if [ "$RUNNING" -eq 0 ]; then
    echo "✅ Все контейнеры остановлены"
else
    echo "⚠️  Остановлено контейнеров: $RUNNING"
fi
echo ""

echo "╔════════════════════════════════════════════════════════════════════════╗"
echo "║ ✅ ШАГ 1.1 ЗАВЕРШЕН                                                   ║"
echo "╚════════════════════════════════════════════════════════════════════════╝"
